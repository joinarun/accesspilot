"""Local Git preparation and approval-bound GitHub pull-request execution."""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
import tempfile
from pathlib import Path

from app.schemas import (
    ApprovalDecision,
    ApprovalRecord,
    FileChange,
    PullRequestDraft,
    WorkflowState,
)

from .errors import AccessPilotError, ApprovalRequired
from .safety import redact_text, validate_editable_path
from .verification import verification_fingerprint

_SAFE_GIT_PREFIX = ["git", "-c", "core.hooksPath=/dev/null"]


class GitService:
    def is_repository(self, root: Path) -> bool:
        return (root / ".git").exists()

    def ensure_local_branch(self, root: Path, branch_name: str) -> None:
        if not self.is_repository(root):
            return
        current = self._run(
            [*_SAFE_GIT_PREFIX, "branch", "--show-current"], root
        ).stdout.strip()
        if current == branch_name:
            return
        existing = self._run(
            [*_SAFE_GIT_PREFIX, "branch", "--list", branch_name],
            root,
            check=False,
        ).stdout.strip()
        if existing:
            self._run([*_SAFE_GIT_PREFIX, "switch", branch_name], root)
        else:
            self._run([*_SAFE_GIT_PREFIX, "switch", "-c", branch_name], root)

    def head_sha(self, root: Path) -> str | None:
        if not self.is_repository(root):
            return None
        return (
            self._run([*_SAFE_GIT_PREFIX, "rev-parse", "HEAD"], root).stdout.strip()
            or None
        )

    def build_pr_draft(self, state: WorkflowState) -> PullRequestDraft:
        verification = state.verification
        fixed = verification.fixed_issue_ids if verification else []
        remaining = verification.remaining_issue_ids if verification else []
        wcag = sorted(
            {
                reference
                for issue in state.issues
                if issue.id in fixed
                for reference in issue.wcag_references
            }
        )
        changed_files = [change.path for change in state.changes]
        affected_routes = sorted(
            {issue.route for issue in state.issues if issue.id in fixed and issue.route}
        )
        checks = []
        if verification:
            checks = [
                f"`{' '.join(check.argv)}` — "
                + (
                    f"skipped ({check.skipped_reason})"
                    if check.skipped_reason
                    else ("passed" if check.exit_code == 0 else "failed")
                )
                for check in verification.checks
            ]
        body = "\n".join(
            [
                "## Summary",
                "",
                f"AccessPilot repaired {len(fixed)} accessibility finding(s) across {len(changed_files)} file(s).",
                "",
                "## Accessibility impact",
                "",
                *(
                    [f"- Fixed `{issue_id}`" for issue_id in fixed]
                    or ["- No issue was automatically resolved."]
                ),
                "",
                f"WCAG references: {', '.join(wcag) if wcag else 'None reported'}",
                "",
                "## Files and pages",
                "",
                "Changed components/files:",
                *(
                    [f"- `{path}`" for path in changed_files]
                    or ["- No source files changed."]
                ),
                "",
                "Affected pages/routes:",
                *(
                    [f"- `{route}`" for route in affected_routes]
                    or ["- No fixed issue route was reported."]
                ),
                "",
                "## Verification",
                "",
                (
                    f"Before: {verification.baseline_issue_count}; after: {verification.current_issue_count}; "
                    f"regressions: {len(verification.regression_issue_ids)}."
                    if verification
                    else "Verification was not available."
                ),
                *checks,
                "",
                "## Known limitations",
                "",
                *(
                    [
                        f"- Remaining issue `{issue_id}` requires review."
                        for issue_id in remaining
                    ]
                    or ["- No scanner-detected findings remain in the scanned routes."]
                ),
                "- Automated checks do not replace assistive-technology and usability testing.",
                "",
                "Generated by AccessPilot; reviewed through its human approval gate.",
            ]
        )
        return PullRequestDraft(
            title=f"Fix accessibility issues in {len(changed_files)} file(s)",
            body=body,
            branch_name=state.request.branch_name,
            base_branch=state.target.default_branch if state.target else None,
            commit_message="fix(a11y): repair verified accessibility issues",
            draft=state.request.draft_pull_request,
            remote_url=state.target.remote_url if state.target else None,
        )

    def publication_fingerprint(self, state: WorkflowState) -> str:
        if not state.pr_draft:
            return ""
        payload = json.dumps(
            state.pr_draft.model_dump(mode="json"),
            sort_keys=True,
            separators=(",", ":"),
        )
        return hashlib.sha256(payload.encode()).hexdigest()

    def execute_pull_request(
        self,
        state: WorkflowState,
        approval: ApprovalRecord,
    ) -> str:
        root = state.workspace()
        if not root or not self.is_repository(root):
            raise AccessPilotError("Pull-request creation requires a Git working copy")
        if not state.verification or not state.pr_draft:
            raise AccessPilotError("Verification and a PR draft are required")
        if not state.verification.passed:
            raise ApprovalRequired(
                "Pull-request creation requires a passing verification report"
            )
        expected_verification = verification_fingerprint(state.verification)
        if (
            approval.decision != ApprovalDecision.APPROVE
            or approval.diff_sha256 != state.verification.diff_sha256
            or approval.verification_fingerprint != expected_verification
            or approval.publication_fingerprint != self.publication_fingerprint(state)
        ):
            raise ApprovalRequired(
                "Approval does not match the current diff and verification report"
            )

        paths_by_change = self._validated_changes(root, state.changes)
        paths = list(paths_by_change)
        if not paths:
            raise AccessPilotError("There are no source changes to publish")
        expected_remote = state.target.remote_url if state.target else None
        if not expected_remote:
            raise ApprovalRequired(
                "Remote publication requires a reviewed repository origin"
            )
        actual_remote = self._run(
            [*_SAFE_GIT_PREFIX, "remote", "get-url", "origin"], root
        ).stdout.strip()
        if actual_remote != expected_remote:
            raise ApprovalRequired("Repository origin changed after review")

        # Branch creation/switching is local-only and deliberately hook-free. The
        # approved commit is checked after it so a branch switch cannot alter the
        # publication base behind the approval gate.
        self.ensure_local_branch(root, state.pr_draft.branch_name)
        current_head = self.head_sha(root)
        if not approval.approved_head or approval.approved_head != current_head:
            raise ApprovalRequired("Repository HEAD changed after approval")

        self._validate_change_hashes(
            root,
            paths_by_change,
            baseline_revision=approval.approved_head,
        )
        self._reject_unapproved_paths(root, set(paths))

        # No credentials are made available to index or commit operations.
        self._run([*_SAFE_GIT_PREFIX, "add", "--", *paths], root)
        staged_paths = self._git_path_set(
            root,
            ["diff", "--cached", "--name-only", "--no-renames", "-z", "--"],
        )
        if staged_paths != set(paths):
            raise ApprovalRequired(
                "The staged patch does not exactly match the approved file set"
            )

        # Recheck both the working files and staged blobs after filters and
        # ``git add`` have run. This prevents a clean filter or concurrent change
        # from substituting content after review.
        if self.head_sha(root) != approval.approved_head:
            raise ApprovalRequired("Repository HEAD changed after approval")
        self._validate_change_hashes(
            root,
            paths_by_change,
            baseline_revision=approval.approved_head,
            validate_staged=True,
        )
        self._reject_unapproved_paths(root, set(paths))
        self._run(
            [
                *_SAFE_GIT_PREFIX,
                "commit",
                "--no-verify",
                "-m",
                state.pr_draft.commit_message,
            ],
            root,
        )
        published_head = self.head_sha(root)
        if not published_head or published_head == approval.approved_head:
            raise ApprovalRequired("Git did not create the reviewed commit")
        parent = self._run(
            [*_SAFE_GIT_PREFIX, "rev-parse", f"{published_head}^"], root
        ).stdout.strip()
        if parent != approval.approved_head:
            raise ApprovalRequired("The publication commit has an unapproved parent")
        committed_paths = self._git_path_set(
            root,
            [
                "diff-tree",
                "--no-commit-id",
                "--name-only",
                "-r",
                "--no-renames",
                "-z",
                published_head,
                "--",
            ],
        )
        if committed_paths != set(paths):
            raise ApprovalRequired(
                "The publication commit does not match the approved file set"
            )
        for relative, change in paths_by_change.items():
            committed = self._run(
                [*_SAFE_GIT_PREFIX, "show", f"{published_head}:{relative}"],
                root,
                check=False,
                binary=True,
            )
            if (
                committed.returncode != 0
                or hashlib.sha256(committed.stdout).hexdigest() != change.after_sha256
            ):
                raise ApprovalRequired(
                    "The publication commit does not contain the reviewed content"
                )

        with tempfile.TemporaryDirectory(prefix="accesspilot-auth-") as auth_dir:
            auth_home = self._prepare_auth_home(Path(auth_dir))
            self._run(
                [
                    *_SAFE_GIT_PREFIX,
                    "-c",
                    "credential.helper=",
                    "push",
                    "--no-verify",
                    "--set-upstream",
                    "origin",
                    f"{published_head}:refs/heads/{state.pr_draft.branch_name}",
                ],
                root,
                allow_auth=True,
                auth_home=auth_home,
            )
            existing = self._run(
                ["gh", "pr", "view", state.pr_draft.branch_name, "--json", "url"],
                root,
                check=False,
                allow_auth=True,
                auth_home=auth_home,
            )
            if existing.returncode == 0:
                try:
                    return str(json.loads(existing.stdout)["url"])
                except (json.JSONDecodeError, KeyError):
                    pass
            with tempfile.NamedTemporaryFile(
                "w", encoding="utf-8", suffix=".md"
            ) as body:
                body.write(state.pr_draft.body)
                body.flush()
                argv = [
                    "gh",
                    "pr",
                    "create",
                    "--title",
                    state.pr_draft.title,
                    "--body-file",
                    body.name,
                    "--head",
                    state.pr_draft.branch_name,
                ]
                if state.pr_draft.base_branch:
                    argv.extend(["--base", state.pr_draft.base_branch])
                if state.pr_draft.draft:
                    argv.append("--draft")
                result = self._run(
                    argv,
                    root,
                    allow_auth=True,
                    auth_home=auth_home,
                )
            return result.stdout.strip().splitlines()[-1]

    def _validated_changes(
        self,
        root: Path,
        changes: list[FileChange],
    ) -> dict[str, FileChange]:
        root = root.resolve()
        validated: dict[str, FileChange] = {}
        for change in changes:
            raw_path = root / change.path
            if raw_path.is_symlink():
                raise ApprovalRequired("Approved changes may not contain symlinks")
            path = validate_editable_path(root, change.path)
            relative = path.relative_to(root).as_posix()
            if relative in validated:
                raise ApprovalRequired("Approved changes contain a duplicate path")
            validated[relative] = change
        return validated

    def _validate_change_hashes(
        self,
        root: Path,
        changes: dict[str, FileChange],
        *,
        baseline_revision: str,
        validate_staged: bool = False,
    ) -> None:
        for relative, change in changes.items():
            current_hash = hashlib.sha256((root / relative).read_bytes()).hexdigest()
            if current_hash != change.after_sha256:
                raise ApprovalRequired(
                    "A reviewed source file changed after verification"
                )

            baseline = self._run(
                [
                    *_SAFE_GIT_PREFIX,
                    "show",
                    f"{baseline_revision}:{relative}",
                ],
                root,
                check=False,
                binary=True,
            )
            if baseline.returncode != 0:
                raise ApprovalRequired(
                    "An approved file is not present in the approved Git revision"
                )
            baseline_hash = hashlib.sha256(baseline.stdout).hexdigest()
            if baseline_hash != change.before_sha256:
                raise ApprovalRequired(
                    "The reviewed before-state does not match the approved Git revision"
                )

            if validate_staged:
                staged = self._run(
                    [*_SAFE_GIT_PREFIX, "show", f":{relative}"],
                    root,
                    check=False,
                    binary=True,
                )
                if staged.returncode != 0:
                    raise ApprovalRequired(
                        "An approved file is missing from the staged patch"
                    )
                staged_hash = hashlib.sha256(staged.stdout).hexdigest()
                if staged_hash != change.after_sha256:
                    raise ApprovalRequired(
                        "Staged content does not match the reviewed source content"
                    )

    def _reject_unapproved_paths(self, root: Path, allowed: set[str]) -> None:
        staged = self._git_path_set(
            root,
            ["diff", "--cached", "--name-only", "--no-renames", "-z", "--"],
        )
        worktree = self._git_path_set(
            root,
            ["diff", "--name-only", "--no-renames", "-z", "--"],
        )
        untracked = self._git_path_set(
            root,
            ["ls-files", "--others", "--exclude-standard", "-z", "--"],
        )
        if (staged | worktree | untracked) - allowed:
            raise ApprovalRequired(
                "Repository contains staged, working-tree, or untracked paths "
                "outside the approved file set"
            )

    def _git_path_set(self, root: Path, argv: list[str]) -> set[str]:
        output = self._run([*_SAFE_GIT_PREFIX, *argv], root).stdout
        return {path for path in output.split("\0") if path}

    def _prepare_auth_home(self, root: Path) -> Path:
        root.mkdir(mode=0o700, parents=True, exist_ok=True)
        (root / "gh").mkdir(mode=0o700)
        askpass = root / "git-askpass"
        askpass.write_text(
            "#!/bin/sh\n"
            'case "$1" in\n'
            "  *sername*) printf '%s\\n' 'x-access-token' ;;\n"
            "  *) printf '%s\\n' \"${GH_TOKEN:-${GITHUB_TOKEN:-}}\" ;;\n"
            "esac\n",
            encoding="utf-8",
        )
        askpass.chmod(0o700)
        return root

    def _run(
        self,
        argv: list[str],
        cwd: Path,
        *,
        check: bool = True,
        allow_auth: bool = False,
        auth_home: Path | None = None,
        binary: bool = False,
    ):
        allowed_names = {"PATH", "USER", "TMPDIR", "LANG", "LC_ALL"}
        if not allow_auth:
            allowed_names.add("HOME")
        env = {
            key: value
            for key, value in os.environ.items()
            if key in allowed_names
            or (allow_auth and key in {"GH_TOKEN", "GITHUB_TOKEN"})
        }
        if allow_auth:
            if auth_home is None:
                raise AccessPilotError(
                    "Authenticated commands require an isolated home directory"
                )
            env.update(
                {
                    "HOME": str(auth_home),
                    "GH_CONFIG_DIR": str(auth_home / "gh"),
                    "GIT_ASKPASS": str(auth_home / "git-askpass"),
                    "GIT_CONFIG_NOSYSTEM": "1",
                }
            )
        env["GIT_TERMINAL_PROMPT"] = "0"
        try:
            result = subprocess.run(
                argv,
                cwd=cwd,
                env=env,
                capture_output=True,
                text=not binary,
                timeout=120,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise AccessPilotError(f"Command {argv[0]!r} could not run") from exc
        if check and result.returncode != 0:
            raw_detail = result.stderr or result.stdout
            if isinstance(raw_detail, bytes):
                raw_detail = raw_detail.decode(errors="replace")
            detail = redact_text(raw_detail, limit=2000)
            raise AccessPilotError(f"{argv[0]} failed: {detail}")
        return result


git_service = GitService()
